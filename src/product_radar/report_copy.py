def long_date(value):
    """'2026-10-20' -> '20 October 2026' (month names stay English in both editions)."""
    year, month, day = value[:10].split("-")
    return f"{int(day)} {MONTHS[int(month) - 1]} {year}"


def short_date(value):
    """'2026-10-14...' -> '14 Oct'."""
    _, month, day = value[:10].split("-")
    return f"{int(day)} {MONTHS[int(month) - 1][:3]}"


def month_year(value):
    """'2026-10-14...' -> 'Oct 2026'."""
    year, month, _ = value[:10].split("-")
    return f"{MONTHS[int(month) - 1][:3]} {year}"


def date_window(days):
    """Sorted ISO dates -> '12–19 October 2026', '28 September – 19 October 2026' or one date."""
    if not days:
        return None
    first, last = min(days)[:10], max(days)[:10]
    if first == last:
        return long_date(first)
    (y1, m1, d1), (y2, m2, d2) = first.split("-"), last.split("-")
    if y1 == y2 and m1 == m2:
        return f"{int(d1)}–{int(d2)} {MONTHS[int(m2) - 1]} {y2}"
    if y1 == y2:
        return f"{int(d1)} {MONTHS[int(m1) - 1]} – {int(d2)} {MONTHS[int(m2) - 1]} {y2}"
    return long_date(first) + " – " + long_date(last)
